import { createRequire } from "module";
import { mkdirSync, readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const require = createRequire(import.meta.url);
const solc = require("solc");

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contractsDir = join(root, "contracts");
const outDir = join(root, "src/lib/web3/artifacts");

const sources = {
  "IdentityRegistry.sol": {
    content: readFileSync(join(contractsDir, "IdentityRegistry.sol"), "utf8"),
  },
  "SecurityToken.sol": {
    content: readFileSync(join(contractsDir, "SecurityToken.sol"), "utf8"),
  },
};

const input = {
  language: "Solidity",
  sources,
  settings: {
    optimizer: { enabled: true, runs: 200 },
    outputSelection: {
      "*": {
        "*": ["abi", "evm.bytecode.object"],
      },
    },
  },
};

function findImports(path) {
  if (sources[path]) return { contents: sources[path].content };
  return { error: `File not found: ${path}` };
}

const output = JSON.parse(
  solc.compile(JSON.stringify(input), { import: findImports }),
);

if (output.errors?.length) {
  const fatal = output.errors.filter((e) => e.severity === "error");
  for (const error of output.errors) {
    console.error(error.formattedMessage || error.message);
  }
  if (fatal.length) process.exit(1);
}

mkdirSync(outDir, { recursive: true });

const contracts = ["IdentityRegistry", "SecurityToken"];
const exportLines = [
  "/* Auto-generated by scripts/compile-contracts.mjs — do not edit by hand. */",
  "",
];

for (const name of contracts) {
  const file = `${name}.sol`;
  const artifact = output.contracts[file][name];
  const abi = artifact.abi;
  const bytecode = `0x${artifact.evm.bytecode.object}`;

  if (!artifact.evm.bytecode.object) {
    console.error(`Missing bytecode for ${name}`);
    process.exit(1);
  }

  writeFileSync(
    join(outDir, `${name}.json`),
    JSON.stringify({ contractName: name, abi, bytecode }, null, 2),
  );

  exportLines.push(
    `import ${name}Json from "./${name}.json";`,
    `export const ${name}Artifact = ${name}Json as {`,
    `  contractName: string;`,
    `  abi: readonly unknown[];`,
    `  bytecode: \`0x\${string}\`;`,
    `};`,
    "",
  );

  console.log(`Compiled ${name} (${bytecode.length / 2 - 1} bytes)`);
}

writeFileSync(join(outDir, "index.ts"), exportLines.join("\n"));
console.log("Artifacts written to src/lib/web3/artifacts");
